def _eval_files(root: Path, agent_name: str, module_name: str) -> dict[Path, str]:
    eval_dir = root / "evals" / module_name
    return {
        eval_dir / "README.md": f"""# {agent_name} evaluations

Replace the fail-closed placeholder in `run.py` with Pydantic Evals datasets and
evaluators. Preserve the normalized report fields consumed by `agentctl`.
""",
        eval_dir / "run.py": _eval_runner(agent_name),
        eval_dir / "release-policy.yaml": _release_policy(),
        eval_dir / "datasets" / "smoke" / ".gitkeep": "",
        eval_dir / "datasets" / "regression" / ".gitkeep": "",
        eval_dir / "datasets" / "safety" / ".gitkeep": "",
        eval_dir / "baselines" / ".gitkeep": "",
    }


