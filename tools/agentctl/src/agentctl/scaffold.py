from __future__ import annotations

import argparse
import re
from datetime import date, timedelta
from pathlib import Path

from agentctl.ui import status, step, success

NAME_PATTERN = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
PACKAGE_PATTERN = re.compile(r"^[a-z_][a-z0-9_]*$")


def _write_files(files: dict[Path, str], *, force: bool) -> None:
    existing = [path for path in files if path.exists()]
    if existing and not force:
        rendered = "\n".join(f"  - {path}" for path in existing)
        raise ValueError(f"refusing to overwrite existing files:\n{rendered}")
    for path, content in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")


def scaffold_agent(args: argparse.Namespace) -> int:
    if not NAME_PATTERN.fullmatch(args.name):
        raise ValueError(
            "agent name must be lowercase letters, digits, and single hyphens"
        )
    if not PACKAGE_PATTERN.fullmatch(args.package):
        raise ValueError("package must be a valid lowercase Python package name")

    root = args.root.resolve()
    module_name = args.name.replace("-", "_")
    agent_dir = root / "src" / args.package / "agents" / module_name
    temporal = args.with_temporal or args.execution_class != "ephemeral"

    files: dict[Path, str] = {
        agent_dir / "__init__.py": '"""Agent package generated by agentctl."""\n',
        agent_dir / "agent.yaml": _agent_spec(args, module_name, temporal),
        agent_dir / "factory.py": _factory(args.package, module_name),
        agent_dir / "dependencies.py": _dependencies(),
        agent_dir / "models.py": _models(),
        agent_dir / "instructions" / "base.md": _instructions(args.name),
        agent_dir / "skills" / ".gitkeep": "",
        agent_dir / "tools" / ".gitkeep": "",
        root / "docs" / "risk-assessments" / f"{args.name}.yaml": _risk_assessment(
            args
        ),
    }

    _add_if_missing(files, root / "src" / args.package / "__init__.py", "")
    _add_if_missing(files, root / "src" / args.package / "agents" / "__init__.py", "")

    if temporal:
        files.update(_temporal_files(root, args.package, module_name))
    if args.execution_class == "human_governed":
        files[
            root / "src" / args.package / "policy" / "approvals" / f"{module_name}.yaml"
        ] = _approval_policy()
    if args.risk_tier in {"medium", "high", "critical"}:
        files[root / "docs" / "threat-models" / f"{args.name}.md"] = _threat_model(
            args.name
        )
    if args.with_evals:
        files.update(_eval_files(root, args.name, module_name))

    with status("Creating the golden-path agent package…"):
        _write_files(files, force=args.force)
    success(
        "Agent scaffold created",
        (
            ("Agent", args.name),
            ("Execution", args.execution_class),
            ("Risk", args.risk_tier),
            ("Files", str(len(files))),
            ("Root", str(root)),
        ),
    )
    step(f"Next: agentctl validate --root {root}")
    if args.with_evals:
        step(f"Then: agentctl eval run {args.name} --root {root}")
    return 0


