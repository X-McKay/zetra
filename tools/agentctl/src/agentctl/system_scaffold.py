def _temporal_files(root: Path, package: str, module_name: str) -> dict[Path, str]:
    workflows = root / "src" / package / "workflows"
    activities = root / "src" / package / "activities"
    files = {
        workflows / f"{module_name}.py": '''"""Deterministic system coordination."""

# Own typed state, graph versions, budgets, routing validation, aggregation,
# termination, approval, cancellation, and compensation here.
''',
        activities / f"{module_name}.py": '''"""Nondeterministic system activities."""

# Run member agents, registries, tools, artifact stores, and other I/O here.
''',
    }
    _add_if_missing(files, workflows / "__init__.py", "")
    _add_if_missing(files, activities / "__init__.py", "")
    return files


