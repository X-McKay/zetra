NAME_PATTERN = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
PACKAGE_PATTERN = re.compile(r"^[a-z_][a-z0-9_]*$")


def scaffold_system(args: argparse.Namespace) -> int:
    if not NAME_PATTERN.fullmatch(args.name):
        raise ValueError("system name must be lowercase hyphenated text")
    if not PACKAGE_PATTERN.fullmatch(args.package):
        raise ValueError("package must be a valid lowercase Python package name")
    if len(args.member) < 2:
        raise ValueError(
            "system scaffold requires at least two --member AGENT:ROLE values"
        )

    root = args.root.resolve()
    members = _resolve_members(root, args.member)
    if len({item["agent"] for item in members}) != len(members):
        raise ValueError("system members must be unique")
    maximum_member_tier = max(
        (item["risk_tier"] for item in members), key=TIER_RANK.__getitem__
    )
    if TIER_RANK[args.risk_tier] < TIER_RANK[maximum_member_tier]:
        raise ValueError(
            f"system risk tier {args.risk_tier} is below member floor {maximum_member_tier}"
        )

    module_name = args.name.replace("-", "_")
    system_dir = root / "src" / args.package / "systems" / module_name
    temporal = args.execution_class != "ephemeral" or args.with_temporal
    spec = _system_spec(args, members, module_name, temporal)

    files: dict[Path, str] = {
        system_dir
        / "__init__.py": '"""Multi-agent system package generated by agentctl."""\n',
        system_dir / "system.yaml": yaml.safe_dump(spec, sort_keys=False),
        system_dir / "factory.py": _factory(),
        system_dir / "models.py": _models(),
        system_dir / "coordination.py": _coordination(),
        system_dir / "policies" / "delegation.yaml": _delegation_policy(spec),
        system_dir / "policies" / "data-flow.yaml": _data_flow_policy(),
        system_dir / "policies" / "termination.yaml": _termination_policy(spec),
        root
        / "docs"
        / "risk-assessments"
        / "systems"
        / f"{args.name}.yaml": _risk_assessment(args, members, maximum_member_tier),
        root / "docs" / "threat-models" / f"{args.name}.md": _threat_model(args.name),
    }
    files.update(_eval_files(root, args.name, module_name))
    _add_if_missing(files, root / "src" / args.package / "__init__.py", "")
    _add_if_missing(files, root / "src" / args.package / "systems" / "__init__.py", "")

    if temporal:
        files.update(_temporal_files(root, args.package, module_name))
    if args.execution_class == "human_governed":
        files[
            root / "src" / args.package / "policy" / "approvals" / f"{module_name}.yaml"
        ] = _approval_policy()
    if args.dynamic_membership:
        files[system_dir / "policies" / "registry.yaml"] = _registry_policy()
        files[system_dir / "policies" / "admission.yaml"] = _admission_policy()

    with status("Creating the golden-path multi-agent system package…"):
        _write_files(files, force=args.force)
    success(
        "Multi-agent system scaffold created",
        (
            ("System", args.name),
            ("Topology", args.topology),
            ("Members", str(len(members))),
            ("Execution", args.execution_class),
            ("Risk", args.risk_tier),
            ("Files", str(len(files))),
            ("Root", str(root)),
        ),
    )
    step(f"Next: agentctl system validate --root {root}")
    step(f"Then: agentctl eval run {args.name} --system --root {root}")
    return 0


def _resolve_members(root: Path, values: list[str]) -> list[dict[str, Any]]:
    resolved: list[dict[str, Any]] = []
    for value in values:
        agent, separator, role = value.partition(":")
        if (
            not separator
            or not NAME_PATTERN.fullmatch(agent)
            or not NAME_PATTERN.fullmatch(role)
        ):
            raise ValueError(f"invalid member {value!r}; expected lowercase AGENT:ROLE")
        matches: list[tuple[Path, dict[str, Any]]] = []
        for path in root.glob("src/*/agents/*/agent.yaml"):
            try:
                spec = load_data(path)
            except DataFileError:
                continue
            if spec.get("name") == agent:
                matches.append((path, spec))
        if not matches:
            raise ValueError(f"member agent {agent!r} was not found under src/*/agents")
        if len(matches) > 1:
            raise ValueError(f"member agent {agent!r} is ambiguous")
        _, spec = matches[0]
        metadata = spec.get("metadata")
        if not isinstance(metadata, dict):
            raise TypeError(f"member agent {agent!r} has invalid metadata")
        resolved.append(
            {
                "agent": agent,
                "role": role,
                "version": metadata.get("version"),
                "execution_class": metadata.get("execution_class"),
                "risk_tier": metadata.get("risk_tier"),
                "risk_assessment": metadata.get("risk_assessment"),
            }
        )
    return resolved


def _system_spec(
    args: argparse.Namespace,
    members: list[dict[str, Any]],
    module_name: str,
    temporal: bool,
) -> dict[str, Any]:
    coordinator = members[0]["agent"]
    interactions = [
        {
            "id": f"delegate-{member['agent']}",
            "from": coordinator,
            "to": member["agent"],
            "mode": "delegate",
            "input_schema": "DelegationRequest",
            "output_schema": "DelegationResult",
            "policy": f"policies/delegation.yaml#delegate-{member['agent']}",
            "max_calls": 2,
            "timeout_seconds": 60,
        }
        for member in members[1:]
    ]
    topology: dict[str, Any] = {
        "type": args.topology,
        "orchestrator": f"{args.name}-workflow",
        "coordinator": coordinator,
        "dynamic_membership": args.dynamic_membership,
        "recursive_delegation": args.recursive_delegation,
    }
    if args.dynamic_membership:
        topology.update(
            {
                "registry": "policies/registry.yaml",
                "admission_policy": "policies/admission.yaml",
            }
        )
    metadata: dict[str, Any] = {
        "contract_version": 1,
        "owner": args.owner,
        "operational_owner": args.operational_owner,
        "version": "0.1.0",
        "execution_class": args.execution_class,
        "governance_tier": args.risk_tier,
        "risk_assessment": f"docs/risk-assessments/systems/{args.name}.yaml",
        "threat_model": f"docs/threat-models/{args.name}.md",
        "evaluation_policy": f"evals/systems/{module_name}/release-policy.yaml",
        "data_classification": "internal",
        "temporal_enabled": temporal,
    }
    if args.execution_class == "human_governed":
        metadata["approval_policy"] = (
            f"src/{args.package}/policy/approvals/{module_name}.yaml"
        )
    return {
        "name": args.name,
        "description": "Replace with the multi-agent system's bounded purpose.",
        "metadata": metadata,
        "justification": {
            "decision_owner": args.owner,
            "review_by": (date.today() + timedelta(days=180)).isoformat(),
            "claimed_benefits": [
                "Replace with a testable benefit over a simpler baseline."
            ],
            "baseline": "replace-with-single-agent-or-deterministic-baseline",
            "evidence": f"artifacts/evals/{args.name}/admission.json",
            "success_measures": ["replace-with-measurable-success-criterion"],
        },
        "topology": topology,
        "members": [
            {
                "agent": item["agent"],
                "version": item["version"],
                "role": item["role"],
                "required": True,
                "restrictions": {
                    "skills": {"include": []},
                    "toolsets": {"include": []},
                    "authorization_scopes_max": [],
                    "data_classification_max": "internal",
                },
            }
            for item in members
        ],
        "interactions": interactions,
        "limits": {
            "max_agent_runs": max(4, len(members) * 2),
            "max_delegation_depth": 2 if args.recursive_delegation else 1,
            "max_parallel_agents": len(members),
            "max_rounds": 3,
            "max_model_requests": max(12, len(members) * 4),
            "max_tool_calls": max(16, len(members) * 6),
            "max_input_tokens": 80000,
            "max_output_tokens": 12000,
            "max_cost_usd": 2.0,
            "deadline_seconds": 180,
        },
        "state": {
            "owner": f"{args.name}-workflow",
            "shared_memory": "none",
            "artifact_policy": "policies/data-flow.yaml",
        },
        "termination": {
            "policy": "policies/termination.yaml",
            "success_states": ["completed"],
            "escalation_state": "escalated-to-human",
        },
    }


def _factory() -> str:
    return '''"""Validated assembly for the multi-agent system."""


def build_system(settings):
    """Resolve pinned members, policies, graph, budgets, and manifest."""
    spec = settings.load_system_spec(__package__)
    members = settings.agent_registry.resolve_members(spec.members)
    policies = settings.policy_registry.resolve_system_policies(spec)
    graph = settings.graph_factory.build(spec.interactions)
    settings.validate_system_contract(spec, members, graph, policies)
    manifest = settings.manifest_factory.build(spec, members, graph, policies)
    return settings.system_runtime(spec, members, graph, policies, manifest)
'''


def _models() -> str:
    return """from typing import Any, Literal

from pydantic import BaseModel, Field


class DelegationRequest(BaseModel):
    delegation_id: str
    objective: str
    input: dict[str, Any]
    depth: int = Field(ge=0)


class DelegationResult(BaseModel):
    delegation_id: str
    status: Literal["completed", "needs_information", "escalated", "failed"]
    output: dict[str, Any] | None = None
    evidence_refs: list[str] = []
"""


def _coordination() -> str:
    return '''"""Deterministic graph, authorization, budget, and termination policy."""

# Keep policy decisions typed and deterministic. Agent output proposes work;
# this module validates membership, edge, authority, data, budget, and state
# before the workflow dispatches it.
'''


def _delegation_policy(spec: dict[str, Any]) -> str:
    interactions = {
        item["id"]: {
            "callers": [item["from"]],
            "callees": [item["to"]],
            "mode": item["mode"],
            "authorization_scopes_max": [],
            "data_classification_max": "internal",
            "budget": {
                "max_model_requests": 3,
                "max_tool_calls": 5,
                "max_input_tokens": 20000,
                "max_output_tokens": 3000,
                "max_cost_usd": 0.5,
            },
            "retry": {
                "maximum_attempts": 2,
                "retryable_failures": ["transient_provider", "transient_dependency"],
                "non_retryable_failures": [
                    "invalid_input",
                    "authorization_denied",
                    "policy_blocked",
                    "budget_exhausted",
                ],
            },
            "failure": {"required": True, "on_failure": "escalate"},
        }
        for item in spec["interactions"]
    }
    return yaml.safe_dump(
        {
            "schema_version": 1,
            "defaults": {
                "recursive_delegation": spec["topology"]["recursive_delegation"],
                "share_parent_history": False,
                "forward_credentials": False,
                "require_tenant_binding": True,
                "reserve_budget_before_dispatch": True,
            },
            "interactions": interactions,
        },
        sort_keys=False,
    )


