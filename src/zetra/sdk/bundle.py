"""Compile an agent package into a bundle and its ``zetra.lock``.

The lock is the resolved manifest: everything the runtime needs that the developer did not
write, with digests of everything they did. ``zetra check`` fails when the committed lock
is stale, so a review always sees authority changes even when only Python changed.
"""

from __future__ import annotations

import ast
import hashlib
import importlib
import types
import typing
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml
from pydantic_ai import AgentSpec

from .contracts import Contract, canonical
from .errors import CompileError
from .gateway import gateway_entry
from .project import Project, find_project
from .skills import SkillSet, load_skills
from .spec import capability_entry, load_spec
from .tools import ToolDecl, discover_tools, ensure_importable

LOCK_VERSION = 1
ALLOWED_CONTRACT_IMPORTS = {
    "pydantic",
    "typing",
    "enum",
    "datetime",
    "zetra",
    "__future__",
    "decimal",
    "uuid",
}
TIER_BUDGETS = {
    "T0": {"model_requests": 4, "tool_calls": 4, "seconds": 60, "cost_usd": 0.05},
    "T1": {"model_requests": 6, "tool_calls": 8, "seconds": 120, "cost_usd": 0.10},
    "T2": {"model_requests": 8, "tool_calls": 12, "seconds": 300, "cost_usd": 0.50},
    "T3": {"model_requests": 8, "tool_calls": 12, "seconds": 300, "cost_usd": 0.50},
}


@dataclass
class Bundle:
    name: str
    package_dir: Path
    project: Project
    spec: AgentSpec
    raw_spec: dict[str, Any]
    input_type: type[Contract]
    output_members: tuple[type[Contract], ...]
    tools: list[ToolDecl]
    skill_set: SkillSet | None = None
    mcp: dict[str, list[str]] = field(default_factory=dict)

    @property
    def skills(self) -> dict[str, dict[str, str]]:
        return self.skill_set.lock_entries() if self.skill_set else {}

    @property
    def capabilities(self) -> list[str]:
        caps = {t.capability for t in self.tools}
        caps |= {f"{server}.{tool}" for server, tools in self.mcp.items() for tool in tools}
        return sorted(caps)

    @property
    def tier(self) -> str:
        """T3 exec or an unapproved irreversible write; T2 writes; T1 reads; T0 model only."""
        writes = [t for t in self.tools if t.is_write]
        reversible = self.project.reversible
        if any(
            t.effect == "exec" or not (t.approval or t.capability in reversible) for t in writes
        ):
            return "T3"
        if writes:
            return "T2"
        return "T1" if self.tools or self.mcp else "T0"

    @property
    def budgets(self) -> dict[str, float]:
        return dict(TIER_BUDGETS[self.tier])

    @property
    def durable(self) -> bool:
        return True  # every deployed agent is durable; `zetra run` is the only non-durable mode

    def lock(self) -> dict[str, Any]:
        return {
            "version": LOCK_VERSION,
            "agent": self.name,
            "spec": {
                "digest": f"sha256:{hashlib.sha256(canonical(self.raw_spec).encode()).hexdigest()}",
                "model": self.spec.model,
            },
            "contracts": {
                "input": self.input_type.__name__,
                "output": [m.__name__ for m in self.output_members],
                "input_schema": f"sha256:{hashlib.sha256(canonical(self.input_type.model_json_schema()).encode()).hexdigest()}",
            },
            "tools": {
                t.name: {
                    "capability": t.capability,
                    "effect": t.effect,
                    "receiver": t.resource if t.is_write else None,
                    "approval": {"mode": "human", "ttl": t.ttl or self.project.approval_ttl}
                    if t.approval
                    else ({"mode": "none", "reversible": True} if t.is_write else None),
                    "payload": t.payload_type.__name__ if t.payload_type else None,
                    "injects": sorted(t.injects),
                }
                for t in self.tools
            },
            "mcp": {server: sorted(tools) for server, tools in self.mcp.items()},
            "skills": self.skills,
            "capabilities": self.capabilities,
            "tier": self.tier,
            "budgets": self.budgets,
            "durable_identifiers": {
                "workflow": "zetra.agent",
                "agent": self.name,
                "toolsets": [
                    "tools",
                    *[f"gateway-{s}" for s in sorted(self.mcp)],
                    *(["skills"] if self.skills else []),
                ],
            },
        }

    @property
    def digest(self) -> str:
        return hashlib.sha256(canonical(self.lock()).encode()).hexdigest()

    def lock_text(self) -> str:
        return (
            "# Generated by `zetra check`. Do not edit. The runtime reads this, not the authored files.\n"
            + yaml.safe_dump(self.lock(), sort_keys=True, default_flow_style=False)
        )


def _check_contract_imports(path: Path) -> None:
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    for node in ast.walk(tree):
        names: list[str] = []
        if isinstance(node, ast.Import):
            names = [a.name.split(".")[0] for a in node.names]
        elif isinstance(node, ast.ImportFrom):
            names = [(node.module or "").split(".")[0]] if node.level == 0 else []
        for name in names:
            if name not in ALLOWED_CONTRACT_IMPORTS:
                raise CompileError(
                    "ZT-CON-001",
                    f"contracts.py may not import {name!r}; allowed: {sorted(ALLOWED_CONTRACT_IMPORTS)}",
                    where=str(path),
                )


def _members(output: Any) -> tuple[type[Contract], ...]:
    members = (
        typing.get_args(output)
        if isinstance(output, types.UnionType) or typing.get_origin(output) is typing.Union
        else (output,)
    )
    for member in members:
        if not (isinstance(member, type) and issubclass(member, Contract)):
            raise CompileError("ZT-CON-003", "Output must be a Contract or a union of Contracts")
    return tuple(members)


def load_contracts(package_dir: Path) -> tuple[type[Contract], tuple[type[Contract], ...]]:
    path = package_dir / "contracts.py"
    if not path.is_file():
        raise CompileError("ZT-CON-002", "contracts.py is required", where=str(package_dir))
    _check_contract_imports(path)
    module = importlib.import_module(f"{package_dir.name}.contracts")
    input_type, output = getattr(module, "Input", None), getattr(module, "Output", None)
    if not (isinstance(input_type, type) and issubclass(input_type, Contract)):
        raise CompileError(
            "ZT-CON-003", "contracts.py must bind Input to a Contract subclass", where=str(path)
        )
    if output is None:
        raise CompileError("ZT-CON-003", "contracts.py must bind Output", where=str(path))
    return input_type, _members(output)


def build(package_dir: Path, *, project: Project | None = None) -> Bundle:
    package_dir = package_dir.resolve()
    if not package_dir.name.isidentifier() or package_dir.name != package_dir.name.lower():
        raise CompileError(
            "ZT-PKG-001",
            "the agent directory must be an importable lowercase package name",
            where=str(package_dir),
        )
    project = project or find_project(package_dir)
    spec, raw = load_spec(package_dir / "agent.yaml")
    name = spec.name or package_dir.name.replace("_", "-")
    ensure_importable(package_dir)
    input_type, output_members = load_contracts(package_dir)
    tools = discover_tools(package_dir, input_type)
    bundle = Bundle(name, package_dir, project, spec, raw, input_type, output_members, tools)
    for entry in spec.capabilities:
        kind, arguments = capability_entry(entry)
        if kind == "Skills":
            bundle.skill_set = load_skills(package_dir, project.root, arguments)
        elif kind == "GatewayMCP":
            server, mcp_tools = gateway_entry(arguments)
            if server not in project.gateway:
                raise CompileError(
                    "ZT-MCP-003", f"gateway server {server!r} is not configured in zetra.toml"
                )
            bundle.mcp[server] = mcp_tools
    for decl in bundle.tools:
        if decl.is_write and not decl.approval and decl.capability not in project.reversible:
            raise CompileError(
                "ZT-TOOL-005",
                f"{decl.name} writes {decl.capability} without @approval; list it under [reversible] in zetra.toml",
            )
    return bundle


def lock_status(bundle: Bundle) -> str:
    path = bundle.package_dir / "zetra.lock"
    if not path.is_file():
        return "missing"
    return "current" if path.read_text(encoding="utf-8") == bundle.lock_text() else "stale"


def write_lock(bundle: Bundle) -> Path:
    path = bundle.package_dir / "zetra.lock"
    path.write_text(bundle.lock_text(), encoding="utf-8")
    return path
